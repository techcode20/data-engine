"""Export a run's winning clean() as a standalone, reusable pipeline script.

The engine cleans data but previously never handed back the generated
``clean()`` itself. The emitted file needs only stdlib + pandas — no
data-engine dependency — so it runs anywhere pandas exists (cron, Airflow,
a colleague's laptop).

Only gate-approved code is ever embedded: the emitted ``clean()`` is the
exact function that passed the sandbox AST gate and validation on the
source run (or a dry-run draft, clearly bannered as UNVALIDATED).
"""
import hashlib
import os

try:
    from importlib.metadata import version as _pkg_version
    _ENGINE_VERSION = _pkg_version("data-engine")
except Exception:
    _ENGINE_VERSION = "dev"


def default_pipeline_path(file_path, output_path=None) -> str:
    """ foo.pipeline.py next to the CSV output, else next to the input stem."""
    if output_path:
        root, _ = os.path.splitext(str(output_path))
        return f"{root}.pipeline.py"
    stem = os.path.splitext(os.path.basename(str(file_path)))[0] or "pipeline"
    return f"{stem}.pipeline.py"


def check_pipeline_path(path: str) -> None:
    """Refuse parent-directory escapes, same policy as CSV export paths."""
    parts = str(path).replace("\\", "/").split("/")
    if ".." in parts:
        raise ValueError(f"refusing pipeline path with parent escape: {path!r}")


def _header_text(text: str) -> str:
    """Make free text docstring-safe: backslashes would become escapes like
    backslash-U inside the emitted docstring (a Windows path breaks the
    emitted script), and a literal triple-double-quote would end it early."""
    return str(text).replace("\\", "/").replace('"""', "'''")


def render_pipeline(code: str, *, source: str, rules: str, input_hash: str,
                    schema_json: str, validated: bool) -> str:
    """Build the standalone script text embedding ``code`` verbatim."""
    schema_sha = hashlib.sha256(schema_json.encode("utf-8")).hexdigest()[:16]
    banner = ("VALIDATED clean() — passed sandbox gate + validation"
              if validated else
              "UNVALIDATED DRY-RUN code — review and validate before any real use")
    header = (
        f'"""{banner}.\n'
        f"Auto-generated by data-engine {_ENGINE_VERSION}.\n"
        f"Source: {_header_text(source)}\n"
        f"Rules: {_header_text(rules)}\n"
        f"input_hash: {input_hash}  schema: {schema_sha}\n"
        f"Reproduces the run: read input -> clean() -> export-sanitized CSV.\n"
        f'"""'
    )
    body = "\n".join([
        header,
        "import argparse",
        "import sys",
        "",
        "import pandas as pd",
        "",
        f"VALIDATED = {validated!r}",
        "",
        code.strip(),
        "",
        _SANITIZER_SRC,
        _READER_SRC,
        _MAIN_SRC,
    ])
    return body + "\n"


# Mirrors pre_clean._quote_if_formula (kept inline so the emitted file has
# zero data-engine dependency). Numeric dtypes are never touched.
_SANITIZER_SRC = '''
def _quote_if_formula(v):
    """Neutralize spreadsheet formula injection on CSV export."""
    if not isinstance(v, str):
        return v
    s = v.lstrip()
    if not s:
        return v
    if s[0] in ("=", "@", "|"):
        return "'" + v
    if v[0] in ("\\t", "\\r", "\\n"):
        return "'" + v
    if s[0] in ("-", "+") and (len(s) == 1 or not (s[1].isdigit() or s[1] == ".")):
        return "'" + v
    return v


def _sanitize_export(df):
    df = df.copy()
    for col in df.select_dtypes(include=["object", "string"]).columns:
        df[col] = df[col].map(_quote_if_formula)
    return df
'''.strip()

_READER_SRC = '''
def _read_input(path):
    low = path.lower()
    if low.endswith(".json"):
        df = pd.read_json(path)
    else:
        df = pd.read_csv(path)
    if not isinstance(df, pd.DataFrame):
        df = pd.DataFrame(df)
    return df
'''.strip()

_MAIN_SRC = '''
def main(argv=None):
    ap = argparse.ArgumentParser(description="Replay a data-engine cleaning pipeline.")
    ap.add_argument("--input", required=True, help="Raw input CSV (or JSON)")
    ap.add_argument("--output", required=True, help="Cleaned output CSV")
    a = ap.parse_args(argv)
    df = _read_input(a.input)
    out = clean(df)
    if not isinstance(out, pd.DataFrame):
        raise SystemExit(f"clean() must return a pandas DataFrame, got {type(out).__name__}")
    _sanitize_export(out).to_csv(a.output, index=False)
    print(f"Wrote {a.output} ({len(out)} rows from {len(df)})")


if __name__ == "__main__":
    main()
'''.strip()


def write_pipeline(path: str, text: str) -> str:
    """Write the rendered script (traversal-checked, owner-read-only)."""
    check_pipeline_path(path)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    try:
        os.chmod(path, 0o600)  # rules text can carry sensitive business context
    except OSError:
        pass
    return path
