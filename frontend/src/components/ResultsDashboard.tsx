function download(name: string, content: string) {
  const blob = new Blob([content], { type: "text/x-python" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}

const PIPELINE_PY = `"""Production pipeline exported from PipelineForge.
Source dataset: northwind_customers_messy.csv
Generated by the autonomous data engine (v3, validated).
"""
import pandas as pd


${CODE_VERSIONS[2]}


if __name__ == "__main__":
    df = pd.read_csv("northwind_customers_messy.csv", dtype=str)
    cleaned = clean(df)
    cleaned.to_csv("cleaned_output.csv", index=False)
    print(f"cleaned {len(cleaned)} rows -> cleaned_output.csv")
`;

const SCHEMA_PY = `"""Pandera schema exported from PipelineForge."""
import pandera.pandas as pa
from pandera import Check, Column

TARGET_SCHEMA_JSON = '''${TARGET_SCHEMA}'''

schema = pa.DataFrameSchema({
    "customer_id": Column(int, nullable=False, unique=True, checks=Check.greater_than_or_equal_to(1)),
    "name": Column(str, nullable=False),
    "signup_date": Column("datetime64[ns]", nullable=False),
    "email": Column(str, nullable=False, checks=Check.str_contains("@")),
    "plan": Column(str, nullable=False, checks=Check.isin(["FREE", "BASIC", "PRO"])),
    "revenue": Column(float, nullable=False, checks=Check.greater_than_or_equal_to(0)),
    "is_active": Column(bool, nullable=False),
    "signup_source": Column(str, nullable=True),
})
`;

const TESTS_PY = `"""Regression tests exported from PipelineForge."""
import pandas as pd

from pipeline import clean
from schema import schema


def test_pipeline_passes_schema():
    df = pd.read_csv("northwind_customers_messy.csv", dtype=str)
    cleaned = clean(df)
    schema.validate(cleaned)  # raises SchemaErrors on failure


def test_no_silent_mass_deletion():
    df = pd.read_csv("northwind_customers_messy.csv", dtype=str)
    cleaned = clean(df)
    assert len(cleaned) / len(df) >= 0.25, "dropped more than 75% of rows"


def test_expected_survivors():
    df = pd.read_csv("northwind_customers_messy.csv", dtype=str)
    cleaned = clean(df)
    assert set(cleaned["customer_id"].astype(int)) == {101, 102, 106, 108, 109}
`;

export function ResultsDashboard() {
  const { phase, attempt, maxRetries, score } = usePipeline();
  const done = phase === "done";
  const dropped = DATASET_META.rowsIn - DATASET_META.rowsOut;

  const stats = [
    { label: "Retries used", value: `${Math.min(attempt, 3) - 1} / ${maxRetries}`, raw: null as number | null },
    { label: "Runtime", value: "≈31s scripted", raw: null },
    { label: "Rows cleaned", value: `${DATASET_META.rowsOut}`, raw: DATASET_META.rowsOut },
    { label: "Rows dropped", value: `${dropped}`, raw: dropped },
    { label: "Quality score", value: `${score}`, raw: score },
  ];

  return (
    <Section
      kicker="Results dashboard"
      title="The run, at a glance"
      blurb="Take the validated artifacts with you — the exact function that passed, its schema, and regression tests."
      action={
        <button
          onClick={() => {
            download("pipeline.py", PIPELINE_PY);
            download("schema.py", SCHEMA_PY);
            download("tests.py", TESTS_PY);
          }}
          disabled={!done}
          className="inline-flex items-center gap-2 rounded-xl bg-gradient-to-r from-[#22d3ee] to-[#0ea5e9] px-5 py-2.5 text-sm font-bold text-black shadow-lg shadow-[#22d3ee]/25 transition hover:brightness-110 disabled:cursor-not-allowed disabled:opacity-40"
        >
          <Download size={15} aria-hidden /> Export pipeline.py + tests.py + schema.py
        </button>
      }
    >
      {!done && (
        <p className="mb-4 rounded-xl border border-white/10 bg-white/[0.02] px-4 py-2.5 text-sm text-[#5b6478]">
          Stats unlock when the run completes — export included.
        </p>
      )}
      <div className="grid grid-cols-2 gap-3 sm:grid-cols-5">
        {stats.map((s, i) => (
          <div key={s.label} className="glass rounded-2xl p-4 text-center">
            <p className="flex items-center justify-center gap-1.5 text-[11px] uppercase tracking-widest text-[#5b6478]">
              {i === 0 && <Timer size={11} aria-hidden />}
              {i === 4 && <Trophy size={11} aria-hidden />}
              {i === 3 && <Trash2 size={11} aria-hidden />}
              {s.label}
            </p>
            <p className="mt-1 text-2xl font-extrabold">
              {s.raw != null && done ? <CountUp value={s.raw} /> : s.raw != null && !done ? "—" : s.value}
            </p>
          </div>
        ))}
      </div>
      {done && (
        <p className="mt-4 font-code text-xs leading-relaxed text-[#5b6478]">
          cleaned ids: {CLEAN_ROWS.map((r) => r.customer_id).join(", ")} · dropped: empty name ×1, bad date ×1,
          bad email+plan+revenue ×1, duplicate id ×1, bad plan ×1
        </p>
      )}
    </Section>
  );
}
